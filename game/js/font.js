/* Fonte bitmap 5x7 (maiúsculas, com acentos do português por composição). */
(function () {
  'use strict';
  const NI = window.NI;
  const G = {}; // glifos: 7 linhas separadas por "/"
  const def = (chars, rows) => { G[chars] = rows; };
  def('A', '.###./#...#/#...#/#####/#...#/#...#/#...#');
  def('B', '####./#...#/#...#/####./#...#/#...#/####.');
  def('C', '.###./#...#/#..../#..../#..../#...#/.###.');
  def('D', '####./#...#/#...#/#...#/#...#/#...#/####.');
  def('E', '#####/#..../#..../####./#..../#..../#####');
  def('F', '#####/#..../#..../####./#..../#..../#....');
  def('G', '.###./#...#/#..../#.###/#...#/#...#/.###.');
  def('H', '#...#/#...#/#...#/#####/#...#/#...#/#...#');
  def('I', '.###./..#../..#../..#../..#../..#../.###.');
  def('J', '..###/...#./...#./...#./...#./#..#./.##..');
  def('K', '#...#/#..#./#.#../##.../#.#../#..#./#...#');
  def('L', '#..../#..../#..../#..../#..../#..../#####');
  def('M', '#...#/##.##/#.#.#/#.#.#/#...#/#...#/#...#');
  def('N', '#...#/##..#/#.#.#/#..##/#...#/#...#/#...#');
  def('O', '.###./#...#/#...#/#...#/#...#/#...#/.###.');
  def('P', '####./#...#/#...#/####./#..../#..../#....');
  def('Q', '.###./#...#/#...#/#...#/#.#.#/#..#./.##.#');
  def('R', '####./#...#/#...#/####./#.#../#..#./#...#');
  def('S', '.####/#..../#..../.###./....#/....#/####.');
  def('T', '#####/..#../..#../..#../..#../..#../..#..');
  def('U', '#...#/#...#/#...#/#...#/#...#/#...#/.###.');
  def('V', '#...#/#...#/#...#/#...#/#...#/.#.#./..#..');
  def('W', '#...#/#...#/#...#/#.#.#/#.#.#/##.##/#...#');
  def('X', '#...#/#...#/.#.#./..#../.#.#./#...#/#...#');
  def('Y', '#...#/#...#/.#.#./..#../..#../..#../..#..');
  def('Z', '#####/....#/...#./..#../.#.../#..../#####');
  def('0', '.###./#...#/#..##/#.#.#/##..#/#...#/.###.');
  def('1', '..#../.##../..#../..#../..#../..#../.###.');
  def('2', '.###./#...#/....#/...#./..#../.#.../#####');
  def('3', '.###./#...#/....#/..##./....#/#...#/.###.');
  def('4', '...#./..##./.#.#./#..#./#####/...#./...#.');
  def('5', '#####/#..../####./....#/....#/#...#/.###.');
  def('6', '.###./#..../#..../####./#...#/#...#/.###.');
  def('7', '#####/....#/...#./..#../.#.../.#.../.#...');
  def('8', '.###./#...#/#...#/.###./#...#/#...#/.###.');
  def('9', '.###./#...#/#...#/.####/....#/....#/.###.');
  def('.', '...../...../...../...../...../.##../.##..');
  def(',', '...../...../...../...../.##../..#../.#...');
  def(':', '...../.##../.##../...../.##../.##../.....');
  def(';', '...../.##../.##../...../.##../..#../.#...');
  def('!', '..#../..#../..#../..#../..#../...../..#..');
  def('?', '.###./#...#/....#/...#./..#../...../..#..');
  def('-', '...../...../...../#####/...../...../.....');
  def('+', '...../..#../..#../#####/..#../..#../.....');
  def('=', '...../...../#####/...../#####/...../.....');
  def('/', '....#/....#/...#./..#../.#.../#..../#....');
  def('\\', '#..../#..../.#.../..#../...#./....#/....#');
  def('(', '...#./..#../.#.../.#.../.#.../..#../...#.');
  def(')', '.#.../..#../...#./...#./...#./..#../.#...');
  def('[', '.###./.#.../.#.../.#.../.#.../.#.../.###.');
  def(']', '.###./...#./...#./...#./...#./...#./.###.');
  def('<', '...#./..#../.#.../#..../.#.../..#../...#.');
  def('>', '.#.../..#../...#./....#/...#./..#../.#...');
  def('*', '...../#.#.#/.###./#####/.###./#.#.#/.....');
  def('%', '##..#/##..#/...#./..#../.#.../#..##/#..##');
  def("'", '..#../..#../.#.../...../...../...../.....');
  def('"', '.#.#./.#.#./...../...../...../...../.....');
  def('_', '...../...../...../...../...../...../#####');
  def('#', '.#.#./.#.#./#####/.#.#./#####/.#.#./.#.#.');
  def('&', '.##../#..#./#.#../.#.../#.#.#/#..#./.##.#');
  def('^', '..#../.#.#./#...#/...../...../...../.....');
  def('~', '...../...../.##.#/#.##./...../...../.....');
  def('|', '..#../..#../..#../..#../..#../..#../..#..');
  def('@', '.###./#...#/#.###/#.#.#/#.###/#..../.###.');
  def('°', '.##../#..#./#..#./.##../...../...../.....');
  def('$', '..#../.####/#.#../.###./..#.#/####./..#..');
  def('→', '...../..#../...#./#####/...#./..#../.....');
  def('←', '...../..#../.#.../#####/.#.../..#../.....');
  def('↑', '..#../.###./#.#.#/..#../..#../..#../..#..');
  def('↓', '..#../..#../..#../..#../#.#.#/.###./..#..');
  def('≠', '....#/...#./#####/..#../#####/.#.../#....');
  def('≈', '...../.##.#/#.##./...../.##.#/#.##./.....');
  def('×', '...../#...#/.#.#./..#../.#.#./#...#/.....');
  def('·', '...../...../...../..#../...../...../.....');
  def('≥', '#..../.#.../..#../.#.../#..../...../#####');
  def('≤', '....#/...#./..#../...#./....#/...../#####');
  def('¬', '...../...../#####/....#/...../...../.....');
  def('♥', '...../.#.#./#####/#####/.###./..#../.....');
  def('█', '#####/#####/#####/#####/#####/#####/#####');
  def('▲', '..#../..#../.###./.###./#####/#####/.....');
  def(' ', '...../...../...../...../...../...../.....');

  const MARKS = { // acentos: 2 linhas acima do glifo
    '́': ['...#.', '..#..'], '̀': ['.#...', '..#..'], '̂': ['..#..', '.#.#.'],
    '̃': ['.##.#', '#.##.'], '̈': ['.#.#.', '.....']
  };
  const CELL_W = 5, CELL_H = 10, BODY_Y = 2;
  const SUBS = { '₂': '2', '²': '2', '³': '3', 'ⁿ': 'n', '−': '-', '–': '-', '—': '-', '“': '"', '”': '"', '‘': "'", '’': "'", '…': '...', 'Σ': 'S', '⊕': '+', '∑': 'S', 'ψ': 'Y', 'α': 'A', 'β': 'B', '\u00a0': ' ' };
  const norm = t => String(t).replace(/[^\u0000-\u024f→←↑↓≠≈×·≥≤¬♥█▲°]/g, c => SUBS[c] || '?').replace(/[₂²³ⁿ−–—“”‘’…Σ⊕∑ψαβ]/g, c => SUBS[c] || c);
  const cache = {};

  function glyphCanvas(ch, color) {
    const key = ch + color;
    if (cache[key]) return cache[key];
    const nf = ch.normalize('NFD'), base = nf[0], marks = nf.slice(1);
    const rows = G[base] || G['?'];
    const c = document.createElement('canvas'); c.width = CELL_W; c.height = CELL_H;
    const g = c.getContext('2d'); g.fillStyle = color;
    rows.split('/').forEach((r, y) => { for (let x = 0; x < 5; x++) if (r[x] === '#') g.fillRect(x, y + BODY_Y, 1, 1); });
    for (const m of marks) {
      if (m === '̧') g.fillRect(2, BODY_Y + 7, 1, 1); // cedilha
      else if (MARKS[m]) MARKS[m].forEach((r, y) => { for (let x = 0; x < 5; x++) if (r[x] === '#') g.fillRect(x, y, 1, 1); });
    }
    return cache[key] = c;
  }

  const F = NI.font = {
    adv: 6,
    width(text, scale = 1) { return Math.max(0, String(text).length * 6 - 1) * scale; },
    // (x,y) = canto superior do corpo da letra; acentos sobem 2px
    draw(g, text, x, y, color = NI.PAL.W, scale = 1, align = 'l', shadow = null) {
      text = norm(String(text).toLocaleUpperCase('pt-BR').normalize('NFC'));
      const w = F.width(text, scale);
      if (align === 'c') x -= Math.round(w / 2); else if (align === 'r') x -= w;
      x = Math.round(x); y = Math.round(y);
      const pass = (cx, cy, col) => {
        let px = cx;
        for (const ch of text) { g.drawImage(glyphCanvas(ch, col), 0, 0, CELL_W, CELL_H, px, cy - BODY_Y * scale, CELL_W * scale, CELL_H * scale); px += 6 * scale; }
      };
      if (shadow) pass(x + scale, y + scale, shadow);
      pass(x, y, color);
    },
    // quebra de linha por largura em pixels; retorna array de linhas
    wrap(text, maxW, scale = 1) {
      const words = norm(text).split(' '), lines = []; let cur = '';
      for (const w of words) {
        const t = cur ? cur + ' ' + w : w;
        if (F.width(t, scale) <= maxW || !cur) cur = t; else { lines.push(cur); cur = w; }
      }
      if (cur) lines.push(cur);
      return lines;
    },
    para(g, text, x, y, maxW, color, scale = 1, lh = 10, align = 'l', shadow = null) {
      const lines = F.wrap(norm(String(text).toLocaleUpperCase('pt-BR')), maxW, scale);
      lines.forEach((l, i) => F.draw(g, l, align === 'c' ? x + maxW / 2 : x, y + i * lh * scale, color, scale, align, shadow));
      return lines.length;
    },
    norm,
    has: ch => !!G[ch.normalize('NFD')[0]]
  };
})();
